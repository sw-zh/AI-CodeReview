[CmdletBinding()]
param(
    [switch]$Rebuild
)

$ErrorActionPreference = "Stop"
Set-StrictMode -Version Latest

$repoRoot = $PSScriptRoot
$composeFile = Join-Path $repoRoot "infra/docker-compose.yml"
$environmentFile = Join-Path $repoRoot "infra/.env"
$composeProject = Split-Path (Split-Path $composeFile -Parent) -Leaf
$postgresDataVolume = "${composeProject}_postgres-data"

function New-LocalSecret {
    param([int]$ByteLength)

    $bytes = New-Object byte[] $ByteLength
    $random = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try {
        $random.GetBytes($bytes)
    }
    finally {
        $random.Dispose()
    }

    return (($bytes | ForEach-Object { $_.ToString("x2") }) -join "")
}

function Invoke-Compose {
    param([string[]]$ComposeArguments)

    & docker compose --env-file $environmentFile -f $composeFile @ComposeArguments
    if ($LASTEXITCODE -ne 0) {
        throw "Docker Compose failed: docker compose $($ComposeArguments -join ' ')"
    }
}

function Wait-ForApiReady {
    $deadline = (Get-Date).AddSeconds(120)
    $readyUrl = "http://localhost:8000/api/v1/health/ready"

    while ((Get-Date) -lt $deadline) {
        try {
            $response = Invoke-WebRequest -Uri $readyUrl -UseBasicParsing -TimeoutSec 5
            if ($response.StatusCode -eq 200) {
                return
            }
        }
        catch {
            # The service is still starting.
        }
        Start-Sleep -Seconds 2
    }

    throw "API did not become ready within 120 seconds. Run: docker compose --env-file infra/.env -f infra/docker-compose.yml logs api"
}

if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
    throw "Docker was not found. Install and start Docker Desktop first."
}

& docker info *> $null
if ($LASTEXITCODE -ne 0) {
    throw "Docker Engine is not running. Start Docker Desktop and try again."
}

& docker compose version *> $null
if ($LASTEXITCODE -ne 0) {
    throw "Docker Compose V2 is unavailable. Upgrade Docker Desktop and try again."
}

if (-not (Test-Path -LiteralPath $environmentFile)) {
    & docker volume inspect $postgresDataVolume *> $null
    if ($LASTEXITCODE -eq 0) {
        throw "Existing PostgreSQL data volume '$postgresDataVolume' was found, but infra/.env is missing. Restore the original POSTGRES_PASSWORD in infra/.env or remove that volume only when its data can be discarded."
    }

    $postgresPassword = New-LocalSecret -ByteLength 24
    $jwtSecret = New-LocalSecret -ByteLength 48
    @"
# Generated by start.ps1 for local development. Do not commit this file.
POSTGRES_DB=ai_codereview
POSTGRES_USER=ai_codereview
POSTGRES_PASSWORD=$postgresPassword
JWT_SECRET=$jwtSecret
GENERATION_PROVIDER=deepseek
GENERATION_MODEL=deepseek-v4-flash
GENERATION_BASE_URL=https://api.deepseek.com
EMBEDDING_PROVIDER=dashscope
EMBEDDING_MODEL=text-embedding-v4
EMBEDDING_BASE_URL=https://dashscope.aliyuncs.com/compatible-mode/v1
EMBEDDING_DIMENSIONS=768
"@ | Set-Content -LiteralPath $environmentFile -Encoding utf8
    Write-Host "Generated local configuration: infra/.env"
}

Write-Host "Starting PostgreSQL..."
Invoke-Compose -ComposeArguments @("up", "-d", "postgres")

Write-Host "Running database migrations..."
if ($Rebuild) {
    Invoke-Compose -ComposeArguments @("run", "--rm", "--build", "migrate")
}
else {
    Invoke-Compose -ComposeArguments @("run", "--rm", "migrate")
}

Write-Host "Starting API, worker, and frontend..."
if ($Rebuild) {
    Invoke-Compose -ComposeArguments @("up", "-d", "--build", "api", "worker", "frontend")
}
else {
    Invoke-Compose -ComposeArguments @("up", "-d", "api", "worker", "frontend")
}

Write-Host "Waiting for API readiness..."
Wait-ForApiReady

Write-Host "Creating demo users..."
Invoke-Compose -ComposeArguments @("exec", "-T", "api", "python", "-m", "app.management.seed_demo_users")

Write-Host "Startup complete."
Write-Host "Frontend: http://localhost:5173"
Write-Host "API docs: http://localhost:8000/docs"
Write-Host "Submitter: submitter@example.local / demo-submitter"
Write-Host "Reviewer: reviewer@example.local / demo-reviewer"
